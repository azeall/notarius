import { demoMode } from '@/lib/data'

/**
 * Полоса «это демонстрация».
 *
 * Сайт показывают покупателям, поэтому он наполнен правдоподобно: имя,
 * адрес, часы приёма. Без пометки такая страница читается как сайт
 * действующего нотариуса — а нотариат профессия, где выдавать вымышленное
 * лицо за настоящее нельзя. Полоса видна на каждой странице и не убирается.
 *
 * Когда сайт заводят настоящему нотариусу, demoMode ставят в false,
 * и полоса исчезает вместе с этим компонентом.
 */
export default function DemoRibbon() {
  if (!demoMode) return null

  return (
    <div
      role="note"
      style={{
        position: 'relative',
        zIndex: 60,
        background: '#b89a5a',
        color: '#0a1628',
        textAlign: 'center',
        padding: '9px 16px',
        fontSize: '13px',
        fontWeight: 600,
        lineHeight: 1.45,
      }}
    >
      Демонстрационный сайт. Нотариус, адрес и телефон вымышлены —
      это образец того, как выглядит готовая работа.
    </div>
  )
}
