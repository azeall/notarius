// ─────────────────────────────────────────────
//  ПРАЙС — единственное место, где правятся цены
//
//  Раньше таблица лежала прямо в разметке страницы /prices, а калькулятор
//  на главной держал свой отдельный список тарифов. Два списка на одни и те
//  же услуги расходятся при первой правке: нотариус поднимает УПТХ в таблице,
//  а калькулятор продолжает считать по-старому — и называет клиенту цену,
//  которой нет.
//
//  Теперь список один. Услуга попадает в калькулятор, если у неё заполнено
//  поле calc; строки без него просто показываются в таблице.
//
//  Тарифы (первая колонка) установлены Налоговым кодексом и одинаковы у всех
//  нотариусов — их трогать не нужно. УПТХ утверждает нотариальная палата
//  региона, он у каждого свой: правится вторая и третья колонки.
// ─────────────────────────────────────────────

export interface CalcSpec {
  id: string
  label: string
  tariff?: number        // фиксированный нотариальный тариф, ₽
  tariffPercent?: number // процент от суммы сделки
  uptx?: number          // УПТХ, ₽
  perPage?: number       // ₽ за страницу
  needsSum?: boolean
  needsPages?: boolean
}

export interface PriceRow {
  name: string
  tariff: string
  uptx: string
  total: string
  calc?: CalcSpec
}

export interface PriceSection {
  title: string
  note: string | null
  rows: PriceRow[]
}

